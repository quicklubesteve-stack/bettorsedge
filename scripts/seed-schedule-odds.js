async function seed() {
  console.log("Seeding Official 2026-2027 NFL & NHL Schedule & Live Odds...");

  await prisma.scheduledGame.deleteMany({});
  console.log("Cleared old scheduled games.");

  const allGames = [...NFL_GAMES, ...NHL_GAMES];

  for (const g of allGames) {
    const { safeProps, ...gameData } = g;
    await prisma.scheduledGame.create({
      data: {
        ...gameData,
        safePropsJson: JSON.stringify(safeProps),
      },
    });
    console.log(`Seeded: ${g.gameId} (${g.awayTeam} @ ${g.homeTeam})`);
  }

  console.log(
    `Successfully seeded ${allGames.length} authentic scheduled games with verified live odds & props!`
  );
}

