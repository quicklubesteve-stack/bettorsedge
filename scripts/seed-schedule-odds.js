async function seedSchedule() {
  console.log("=== SEEDING SPORTSEDGE AI GAME SCHEDULE, ODDS & PROPS (2025-2026) ===");

  // Clear existing games to prevent duplicate keys
  await prisma.scheduledGame.deleteMany({});

  const allGames = [...NFL_GAMES, ...NHL_GAMES];

  for (const g of allGames) {
    await prisma.scheduledGame.create({
      data: {
        league: g.league,
        gameId: g.gameId,
        date: g.date,
        week: g.week || 11,
        status: "SCHEDULED",
        homeTeam: g.homeTeam,
        awayTeam: g.awayTeam,
        homeTeamName: g.homeTeamName,
        awayTeamName: g.awayTeamName,
        venue: g.venue,
        broadcast: g.broadcast,
        homeMoneyline: g.homeMoneyline,
        awayMoneyline: g.awayMoneyline,
        spread: g.spread,
        spreadFavorite: g.spreadFavorite,
        overUnder: g.overUnder,
        homeWinProbability: g.homeWinProbability,
        awayWinProbability: g.awayWinProbability,
        predictedWinner: g.predictedWinner,
        predictedScore: g.predictedScore,
        predictedSpreadPick: g.predictedSpreadPick,
        spreadConfidence: g.spreadConfidence,
        predictedOverUnder: g.predictedOverUnder,
        predictionReasoning: g.predictionReasoning,
        firstTeamToScore: g.firstTeamToScore,
        firstTeamOdds: g.firstTeamOdds,
        firstTeamReasoning: g.firstTeamReasoning,
        homeFirstScorer: g.homeFirstScorer,
        homeFirstScorerOdds: g.homeFirstScorerOdds,
        homeFirstScorerReason: g.homeFirstScorerReason,
        awayFirstScorer: g.awayFirstScorer,
        awayFirstScorerOdds: g.awayFirstScorerOdds,
        awayFirstScorerReason: g.awayFirstScorerReason,
        safePropsJson: JSON.stringify(g.safeProps),
      },
    });
    console.log(`Seeded ${g.league} game: ${g.awayTeam} @ ${g.homeTeam} (${g.gameId})`);
  }

  console.log(`Successfully seeded ${allGames.length} scheduled games with odds, spreads & prop predictions!`);
  await prisma.$disconnect();
}

seedSchedule().catch(console.error);
